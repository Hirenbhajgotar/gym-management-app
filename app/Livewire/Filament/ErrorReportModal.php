<?php

namespace App\Livewire\Filament;

use App\Enums\ErrorCategory;
use App\Enums\ErrorPriority;
use App\Services\ErrorReportService;
use Filament\Forms\Components\Grid;
use Filament\Forms\Components\Placeholder;
use Filament\Forms\Components\Section;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Concerns\InteractsWithForms;
use Filament\Forms\Contracts\HasForms;
use Filament\Forms\Form;
use Filament\Notifications\Notification;
use Illuminate\Support\Str;
use Livewire\Attributes\On;
use Livewire\Component;

/**
 * @property Form $form
 */
class ErrorReportModal extends Component implements HasForms
{
    use InteractsWithForms;

    public bool $isOpen = false;

    public ?string $errorMessage;

    public ?string $exceptionId = null;

    public ?array $exceptionData = null;

    // Form properties
    public $error_category;

    public $priority;

    public $description;

    public function mount()
    {
        $this->resetForm();
    }

    #[On('open-error-report-modal')]
    public function openModal($data)
    {
        $this->errorMessage = $data['errorMessage'];
        $this->exceptionId = $data['exceptionId'];
        $this->isOpen = true;

        // Set defaults
        $this->error_category = ErrorCategory::OTHER->value;
        $this->priority = ErrorPriority::MEDIUM->value;
        $this->description = '';

        // Manually fill the form if needed, though public props should auto-bind
        $this->form->fill([
            'error_category' => $this->error_category,
            'priority' => $this->priority,
            'description' => $this->description,
        ]);

        $this->dispatch('open-modal', id: 'error-report-modal');
    }

    public function closeModal()
    {
        $this->resetForm();
        $this->dispatch('close-modal', id: 'error-report-modal');
    }

    private function resetForm()
    {
        $this->isOpen = false;
        $this->errorMessage = '';
        $this->exceptionData = null;
        $this->exceptionId = null;

        $this->error_category = ErrorCategory::OTHER->value;
        $this->priority = ErrorPriority::MEDIUM->value;
        $this->description = '';

        if ($this->form) {
            $this->form->fill([]);
        }
    }

    protected function rules(): array
    {
        return [
            'error_category' => 'required|string',
            'priority' => 'required|string',
            'description' => 'required|string|min:10',
        ];
    }

    public function form(Form $form): Form
    {
        return $form
            ->schema([
                Section::make('Error Details')
                    ->description('Information about the error that occurred')
                    ->icon('heroicon-o-exclamation-triangle')
                    ->schema([
                        Placeholder::make('error_summary')
                            ->label('Error Summary')
                            ->content(fn () => $this->getErrorSummary())
                            ->helperText('This is the technical error message generated by the system')
                            ->columnSpanFull(),
                    ]),

                Section::make('Report Information')
                    ->description('Help us understand what happened')
                    ->icon('heroicon-o-document-text')
                    ->schema([
                        Grid::make(2)
                            ->schema([
                                Select::make('error_category')
                                    ->label('Error Category')
                                    ->options(collect(ErrorCategory::cases())->mapWithKeys(
                                        fn ($method) => [$method->value => $method->getLabel()]
                                    ))
                                    ->default(ErrorCategory::OTHER->value)
                                    ->required()
                                    ->native(false),

                                Select::make('priority')
                                    ->label('Priority Level')
                                    ->options(collect(ErrorPriority::cases())->mapWithKeys(
                                        fn ($method) => [$method->value => $method->getDescriptiveLabel()]
                                    ))
                                    ->default(ErrorPriority::MEDIUM->value)
                                    ->required()
                                    ->native(false),
                            ]),

                        Textarea::make('description')
                            ->label('What were you trying to do?')
                            ->placeholder('Please provide a detailed description of: 1. What you were trying to accomplish, 2. The steps you took before the error occurred, 3. Any additional context that might help us reproduce the issue')
                            ->required()
                            ->rows(6)
                            ->columnSpanFull()
                            ->helperText('The more details you provide, the faster we can resolve the issue'),
                    ]),
            ])
            ->statePath('data');
    }

    private function getErrorSummary(): string
    {
        $shortError = Str::limit($this->errorMessage ?? '', 150);
        $timestamp = now()->format('M j, Y \a\t g:i A');

        return 'Error occurred on ' . $timestamp . ' Brief description: ' . $shortError;
    }

    public function submitReport()
    {
        $this->validate();

        $errorReportService = app(ErrorReportService::class);

        $errorReportService->manuallyReportException(
            userDescription: $this->description,
            priority: $this->priority,
            errorCategory: $this->error_category,
            exceptionId: $this->exceptionId,
        );

        $this->closeModal();

        Notification::make()
            ->title('Error Reported')
            ->body('Thank you for reporting this error. Our team will investigate it.')
            ->success()
            ->send();
    }

    public function render()
    {
        return view('livewire.filament.error-report-modal');
    }
}
